// Colloquy markdown renderer — shared, verbatim, by the browser and the server.
//
// public/app.js imports it to paint live statements; server/export-html.js
// imports it to build the self-contained HTML transcript export, so a
// downloaded debate renders exactly like the one on screen. It is deliberately
// free of DOM and of Node APIs: the only ambient dependency is an optional
// global `katex` (the browser gets it from vendor/katex/katex.min.js, the
// server assigns globalThis.katex from the same vendored file), and every
// entry point degrades to literal text when it is missing.
// ---------------------------------------------------------------
// Safe markdown rendering: escape ALL HTML first, then apply only a
// fixed whitelist of markup. This is the ONLY code path allowed to set
// .innerHTML from model-generated text.
//
// Supported: ATX headings, paragraphs (soft newline -> <br>), bullet and
// numbered lists (nested, tight/loose), blockquotes, fenced and inline
// code, GFM tables, thematic breaks, links (scheme-whitelisted), bold,
// italic, bold-italic, strikethrough. Everything else renders as text.
//
// The order is invariant: escapeHtml runs on every fragment BEFORE any
// tag is introduced. Block structure is detected on the raw lines, but
// only escaped substrings are ever interpolated into the output.
// ---------------------------------------------------------------

export function escapeHtml(str) {
  return String(str).replace(/[&<>"']/g, (ch) => ({
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
  }[ch]));
}

// Exact inverse of escapeHtml. Only ever applied to strings escapeHtml
// itself produced, so the entity set is closed and the round-trip is
// lossless — &amp; must be restored last or "&amp;lt;" would decode twice.
function unescapeHtml(str) {
  return String(str)
    .replace(/&lt;/g, '<').replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"').replace(/&#39;/g, "'")
    .replace(/&amp;/g, '&');
}

// The one exception to the escape-everything rule above: KaTeX emits HTML
// that is NOT run through escapeHtml. It is safe because the markup is
// generated by the typesetter rather than interpolated from input — KaTeX
// escapes every glyph it copies out of the source — and because
// `trust: false` refuses the only macros that can emit a URL or raw HTML
// (\href, \url, \includegraphics, \htmlClass and friends). Do not set
// trust to true, and do not pass user text to any other KaTeX entry point.
//
// Returns null when KaTeX is missing (a vendor/ that failed to load) so
// every call site can fall back to rendering the math as literal text
// instead of throwing halfway through a statement.
const mathCache = new Map();

function renderMath(tex, displayMode) {
  if (typeof katex === 'undefined') return null;
  // updateLiveStatementBody re-renders the WHOLE statement on every
  // streamed token, so the same equation is typeset once per token
  // without this. Keyed on mode + source; bounded, not an LRU.
  const key = `${displayMode ? 'D' : 'I'} ${tex}`;
  const hit = mathCache.get(key);
  if (hit !== undefined) return hit;
  let html;
  try {
    html = katex.renderToString(tex, {
      displayMode,
      throwOnError: false, // malformed TeX renders as red inline text
      strict: false, // don't console-warn on the unicode models happily emit
      trust: false,
    });
  } catch {
    return null; // even with throwOnError, KaTeX can throw on bad options
  }
  if (mathCache.size > 500) mathCache.clear();
  mathCache.set(key, html);
  return html;
}

// Only these schemes may reach an href. Everything else (javascript:,
// data:, vbscript:, …) falls back to rendering the link as plain text.
// The url arrives already escaped, so quotes cannot break the attribute.
function safeUrl(escapedUrl) {
  const probe = escapedUrl.trim().replace(/&amp;/g, '&');
  if (/^(https?:\/\/|mailto:|#|\/|\.{1,2}\/)/i.test(probe)) return escapedUrl.trim();
  return null;
}

// Emphasis rules, applied to already-escaped text. Longest markers first
// so *** wins over ** wins over *. The underscore forms require a
// boundary on both sides so snake_case identifiers survive intact.
function mdEmphasis(s) {
  return s
    .replace(/\*\*\*(?!\s)([\s\S]*?[^\s*])\*\*\*/g, '<strong><em>$1</em></strong>')
    .replace(/\*\*(?!\s)([\s\S]*?[^\s*])\*\*/g, '<strong>$1</strong>')
    .replace(/\*(?!\s)([\s\S]*?[^\s*])\*/g, '<em>$1</em>')
    .replace(/(^|[^\w\\])___(?!\s)([\s\S]*?[^\s_])___(?!\w)/g, '$1<strong><em>$2</em></strong>')
    .replace(/(^|[^\w\\])__(?!\s)([\s\S]*?[^\s_])__(?!\w)/g, '$1<strong>$2</strong>')
    .replace(/(^|[^\w\\])_(?!\s)([\s\S]*?[^\s_])_(?!\w)/g, '$1<em>$2</em>')
    .replace(/~~(?!\s)([\s\S]*?[^\s~])~~/g, '<del>$1</del>');
}

// A bare $ is far more often money than math, so $…$ carries guards the
// unambiguous \(…\) form does not need: no space just inside either
// delimiter, no digit right after the closer (that is what rejects
// "$5 to $10"), and a body that isn't just an amount ("$1,200.00").
const RE_MATH_PAREN = /\\\(([\s\S]+?)\\\)/g;
const RE_MATH_DOLLAR2 = /\$\$([^\n]+?)\$\$/g;
const RE_MATH_DOLLAR1 = /\$(?![\s$])([^$\n]*[^\s$])\$(?!\d)/g;
const RE_MONEY_ONLY = /^[\d\s,.]*$/;

// Inline markup for one already-escaped run of text. Code spans, math and
// link hrefs are lifted out into `frags` before emphasis runs, so a `*`
// inside a code span, a `_` inside a URL, or a `*` inside an equation is
// never mistaken for markup. The placeholders use NUL, which
// renderStatementHTML strips from the input.
function mdInline(escapedText) {
  const frags = [];
  const hold = (html) => `\u0000${frags.push(html) - 1}\u0000`;

  let s = escapedText.replace(/(`+)([\s\S]+?)\1/g, (_, __, code) => hold(`<code>${code}</code>`));

  // Math runs after code spans (so `$5` in backticks stays literal) and
  // before emphasis (so x^{*} and a_i survive). Fenced blocks never reach
  // mdInline at all, so they need no guard here. KaTeX wants the original
  // characters back, hence unescapeHtml; a failed render falls through to
  // the matched text, which is still escaped and therefore still inert.
  const math = (whole, tex, displayMode) => {
    if (!tex.trim()) return whole;
    const html = renderMath(unescapeHtml(tex), displayMode);
    return html === null ? whole : hold(html);
  };
  s = s.replace(RE_MATH_PAREN, (whole, tex) => math(whole, tex, false));
  s = s.replace(RE_MATH_DOLLAR2, (whole, tex) => math(whole, tex, true));
  s = s.replace(RE_MATH_DOLLAR1, (whole, tex) => (
    RE_MONEY_ONLY.test(tex) ? whole : math(whole, tex, false)
  ));

  s = s.replace(
    /\[([^\]\n]*)\]\(\s*([^\s)]*)(?:\s+&quot;[^\n]*?&quot;)?\s*\)/g,
    (whole, text, url) => {
      const href = safeUrl(url);
      if (!href) return whole;
      return hold(`<a href="${href}" target="_blank" rel="noopener noreferrer">${mdEmphasis(text)}</a>`);
    },
  );

  s = mdEmphasis(s);

  // Held fragments can themselves contain placeholders (a code span inside
  // link text), so restore until the string stops changing.
  for (let pass = 0; pass < 5 && s.includes('\u0000'); pass++) {
    s = s.replace(/\u0000(\d+)\u0000/g, (m, i) => frags[Number(i)] ?? m);
  }
  return s;
}

const RE_FENCE = /^ {0,3}(`{3,}|~{3,})\s*([^\s`]*)\s*$/;
const RE_HEADING = /^ {0,3}(#{1,6})\s+(.*?)\s*#*\s*$/;
const RE_HR = /^ {0,3}([-*_])[ \t]*(?:\1[ \t]*){2,}$/;
const RE_QUOTE = /^ {0,3}>/;
const RE_ITEM = /^(\s*)([-*+]|\d{1,9}[.)])(\s+)(.*)$/;
// Display math opening its own line. mdInline only ever sees one line at a
// time, so multi-line math (align environments, \[ on a line by itself)
// has to be recognised as a block here or it would be torn into paragraphs.
const RE_MATH_BLOCK = /^ {0,3}(\$\$|\\\[)/;

// A line that starts a new block interrupts an open paragraph. Models
// routinely omit the blank line before a list, so lists count here.
function startsBlock(line) {
  return RE_FENCE.test(line) || RE_HEADING.test(line) || RE_HR.test(line)
    || RE_QUOTE.test(line) || RE_ITEM.test(line) || RE_MATH_BLOCK.test(line);
}

const indentOf = (line) => line.match(/^\s*/)[0].length;
const isOrderedMarker = (marker) => /\d/.test(marker);

function splitTableRow(line) {
  let s = line.trim();
  if (s.startsWith('|')) s = s.slice(1);
  if (s.endsWith('|')) s = s.slice(0, -1);
  return s.split('|').map((cell) => cell.trim());
}

function tableAlignments(delimLine) {
  return splitTableRow(delimLine).map((cell) => {
    const left = cell.startsWith(':');
    const right = cell.endsWith(':');
    if (left && right) return 'center';
    if (right) return 'right';
    if (left) return 'left';
    return null;
  });
}

// A GFM table needs a header row and a delimiter row whose cell count matches.
function isTableStart(lines, i) {
  const header = lines[i];
  const delim = lines[i + 1];
  if (!header || !delim || !header.includes('|')) return false;
  if (!/^[\s|:-]+$/.test(delim) || !delim.includes('-') || !delim.includes('|')) return false;
  return splitTableRow(header).length === splitTableRow(delim).length;
}

function renderTable(lines, i) {
  const headers = splitTableRow(lines[i]);
  const aligns = tableAlignments(lines[i + 1]);
  let j = i + 2;
  const rows = [];
  while (j < lines.length && lines[j].trim() && lines[j].includes('|')) {
    rows.push(splitTableRow(lines[j]));
    j++;
  }
  const cell = (tag, text, align) => {
    const style = align ? ` style="text-align:${align}"` : '';
    return `<${tag}${style}>${mdInline(escapeHtml(text ?? ''))}</${tag}>`;
  };
  const head = `<tr>${headers.map((h, k) => cell('th', h, aligns[k])).join('')}</tr>`;
  const body = rows
    .map((r) => `<tr>${headers.map((_, k) => cell('td', r[k], aligns[k])).join('')}</tr>`)
    .join('');
  const table = `<table><thead>${head}</thead><tbody>${body}</tbody></table>`;
  return { html: `<div class="md-table-wrap">${table}</div>`, next: j };
}

// Collects one run of sibling list items starting at `lines[i]`. Each item
// keeps its own raw lines (with the marker indent stripped) so nested lists
// and multi-paragraph items recurse back through mdBlocks.
function renderList(lines, i) {
  const first = lines[i].match(RE_ITEM);
  const baseIndent = first[1].length;
  const ordered = isOrderedMarker(first[2]);
  const start = ordered ? parseInt(first[2], 10) : null;
  const items = [];
  let current = null;
  let tight = true;
  let pendingBlank = false;

  while (i < lines.length) {
    const line = lines[i];
    if (!line.trim()) {
      const next = lines[i + 1];
      const continues = next && next.trim()
        && (indentOf(next) > baseIndent || (RE_ITEM.test(next) && indentOf(next) <= baseIndent + 1));
      if (!continues) break;
      pendingBlank = true;
      i++;
      continue;
    }

    const item = line.match(RE_ITEM);
    const indent = indentOf(line);

    if (item && indent <= baseIndent + 1) {
      if (isOrderedMarker(item[2]) !== ordered) break; // a bullet list after a numbered one is a new list
      if (pendingBlank) tight = false;
      current = [item[4]];
      items.push(current);
    } else if (!current) {
      break;
    } else if (indent > baseIndent) {
      if (pendingBlank) { current.push(''); tight = false; }
      // Strip one level of indent so nested markers land at column 0.
      current.push(line.slice(Math.min(indent, baseIndent + first[2].length + first[3].length)));
    } else {
      if (pendingBlank) break; // blank line then unindented text ends the list
      current.push(line.trim()); // lazy continuation of the item's paragraph
    }
    pendingBlank = false;
    i++;
  }

  const html = items
    .map((itemLines) => {
      let inner = mdBlocks(itemLines);
      // Tight items drop the leading <p> so bullets don't gain paragraph
      // spacing. Only the first one — anything after it is a nested list.
      if (tight) inner = inner.replace(/^<p>([\s\S]*?)<\/p>/, '$1');
      return `<li>${inner}</li>`;
    })
    .join('');

  const tag = ordered ? 'ol' : 'ul';
  const startAttr = ordered && start !== 1 ? ` start="${start}"` : '';
  return { html: `<${tag}${startAttr}>${html}</${tag}>`, next: i };
}

// Collects a $$…$$ or \[…\] display-math block starting at `i`, which may
// close on the same line or many lines later. An UNclosed opener renders as
// literal text rather than math: while streaming, the opener arrives many
// tokens before the closer, and typesetting the half-written equation would
// flash KaTeX's red error text on the projector until it completed.
function renderMathBlock(lines, i) {
  const open = lines[i].match(RE_MATH_BLOCK)[1];
  const close = open === '$$' ? '$$' : '\\]';
  const buf = [];
  let rest = lines[i].trim().slice(open.length);
  let j = i;
  let closed = false;

  for (;;) {
    const at = rest.indexOf(close);
    if (at !== -1) { buf.push(rest.slice(0, at)); j++; closed = true; break; }
    buf.push(rest);
    j++;
    if (j >= lines.length) break;
    rest = lines[j];
  }

  const tex = buf.join('\n').trim();
  const html = closed && tex ? renderMath(tex, true) : null;
  if (html !== null) return { html, next: j };
  const literal = lines.slice(i, j).map((l) => escapeHtml(l)).join('<br>');
  return { html: `<p>${literal}</p>`, next: j };
}

// Block-level pass. Every fragment of `lines` that ends up inside the
// returned HTML goes through escapeHtml first; the tags themselves are
// literals chosen here, never derived from the input. The exception is
// display math, whose HTML comes from KaTeX (see renderMath).
function mdBlocks(lines) {
  const out = [];
  let i = 0;

  while (i < lines.length) {
    const line = lines[i];

    if (!line.trim()) { i++; continue; }

    const fence = line.match(RE_FENCE);
    if (fence) {
      const closer = new RegExp(`^ {0,3}${fence[1][0] === '`' ? '`' : '~'}{${fence[1].length},}\\s*$`);
      const buf = [];
      i++;
      while (i < lines.length && !closer.test(lines[i])) { buf.push(lines[i]); i++; }
      i++; // consume the closing fence (a no-op past the end while streaming)
      // ```math / ```latex is display math, not code. Falls through to the
      // normal code block if KaTeX is missing or the TeX is empty.
      const mathHtml = /^(math|latex|tex)$/i.test(fence[2] || '') && buf.join('\n').trim()
        ? renderMath(buf.join('\n').trim(), true)
        : null;
      if (mathHtml !== null) { out.push(mathHtml); continue; }
      const cls = fence[2] ? ` class="lang-${escapeHtml(fence[2])}"` : '';
      out.push(`<pre><code${cls}>${escapeHtml(buf.join('\n'))}</code></pre>`);
      continue;
    }

    if (RE_MATH_BLOCK.test(line)) {
      const math = renderMathBlock(lines, i);
      out.push(math.html);
      i = math.next;
      continue;
    }

    const heading = line.match(RE_HEADING);
    if (heading) {
      const level = heading[1].length;
      out.push(`<h${level}>${mdInline(escapeHtml(heading[2]))}</h${level}>`);
      i++;
      continue;
    }

    if (RE_HR.test(line)) { out.push('<hr>'); i++; continue; }

    if (RE_QUOTE.test(line)) {
      const buf = [];
      // Lazy continuation: unmarked non-blank lines stay inside the quote.
      while (i < lines.length && lines[i].trim() && (RE_QUOTE.test(lines[i]) || buf.length)) {
        buf.push(lines[i].replace(/^ {0,3}>[ \t]?/, ''));
        i++;
      }
      out.push(`<blockquote>${mdBlocks(buf)}</blockquote>`);
      continue;
    }

    if (isTableStart(lines, i)) {
      const table = renderTable(lines, i);
      out.push(table.html);
      i = table.next;
      continue;
    }

    if (RE_ITEM.test(line)) {
      const list = renderList(lines, i);
      out.push(list.html);
      i = list.next;
      continue;
    }

    const buf = [];
    while (i < lines.length && lines[i].trim() && !startsBlock(lines[i]) && !isTableStart(lines, i)) {
      buf.push(lines[i].trim());
      i++;
    }
    // A soft newline inside a paragraph stays a visible break — models use
    // single newlines as line breaks far more often than as reflowable text.
    out.push(`<p>${buf.map((l) => mdInline(escapeHtml(l))).join('<br>')}</p>`);
  }

  return out.join('');
}

// Renders a raw (untrusted) statement into a safe HTML string. Every
// character of `raw` passes through escapeHtml before any tag is ever
// introduced; the markdown passes only wrap already-escaped substrings in
// a fixed whitelist of tags.
export function renderStatementHTML(raw) {
  const text = String(raw).replace(/\u0000/g, '').replace(/\r\n?/g, '\n');
  return mdBlocks(text.split('\n'));
}
